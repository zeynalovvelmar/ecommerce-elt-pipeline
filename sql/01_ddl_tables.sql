-- ======================================================
-- 1. STAGING LAYER (Raw Data Container)
-- ======================================================
-- Note: Data is loaded here via Import Tool from Excel
CREATE TABLE staging_orders (
    order_id              VARCHAR2(100),
    order_ts              VARCHAR2(100),
    order_date            VARCHAR2(100),
    sales_channel         VARCHAR2(100),
    payment_method        VARCHAR2(100),
    device_type           VARCHAR2(100),
    customer_id           VARCHAR2(100),
    customer_name         VARCHAR2(255),
    customer_city         VARCHAR2(100),
    customer_country      VARCHAR2(100),
    segment               VARCHAR2(100),
    delivery_instructions VARCHAR2(4000),
    shipment_id           VARCHAR2(100),
    carrier               VARCHAR2(100),
    shipped_ts            VARCHAR2(100),
    delivered_ts          VARCHAR2(100),
    line_nbr              VARCHAR2(50),
    product_id            VARCHAR2(100),
    sku                   VARCHAR2(100),
    category_code         VARCHAR2(100),
    brand                 VARCHAR2(100),
    quantity              VARCHAR2(50),
    unit_price            VARCHAR2(50),
    discount_rate         VARCHAR2(50),
    line_net_amount       VARCHAR2(50),
    line_vat_amount       VARCHAR2(50),
    shipping_fee          VARCHAR2(50),
    order_discount        VARCHAR2(50),
    grand_total           VARCHAR2(50),
    is_gift               VARCHAR2(50),
    gift_wrap             VARCHAR2(50),
    requires_id_check     VARCHAR2(50),
    promo_stackable       VARCHAR2(50),
    promos_applied_text   VARCHAR2(4000),
    issues_text           VARCHAR2(4000),
    backorder_flag        VARCHAR2(50)
);

-- ======================================================
-- 2. WAREHOUSE LAYER (Star Schema Dimensions)
-- ======================================================

-- Customer Dimension
CREATE TABLE dim_customer (
    customer_sk      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    customer_id      VARCHAR2(50),
    customer_name    VARCHAR2(255),
    customer_city    VARCHAR2(100),
    customer_country VARCHAR2(100),
    segment          VARCHAR2(50)
);

-- Product Dimension
CREATE TABLE dim_product (
    product_sk    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    product_id    VARCHAR2(50),
    sku           VARCHAR2(50),
    brand         VARCHAR2(100),
    category_code VARCHAR2(50)
);

-- Shipment Dimension
CREATE TABLE dim_shipment (
    shipment_sk           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    shipment_id           VARCHAR2(50),
    carrier               VARCHAR2(50),
    delivery_instructions VARCHAR2(4000),
    shipped_ts            TIMESTAMP,
    delivered_ts          TIMESTAMP
);

-- Junk Dimension (Flags & Low Cardinality Attributes)
CREATE TABLE dim_junk (
    junk_sk           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    sales_channel     VARCHAR2(50),
    payment_method    VARCHAR2(50),
    device_type       VARCHAR2(50),
    is_gift           VARCHAR2(5),
    gift_wrap         VARCHAR2(5),
    requires_id_check VARCHAR2(5),
    promo_stackable   VARCHAR2(5)
);

-- Date Dimension
CREATE TABLE dim_date (
    date_sk   NUMBER PRIMARY KEY, -- Format: YYYYMMDD
    full_date DATE,
    year      NUMBER,
    month     NUMBER,
    day_name  VARCHAR2(20)
);

-- ======================================================
-- 3. FACT TABLE (Transactional Grain)
-- ======================================================

CREATE TABLE fact_sales (
    sales_sk        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    order_id        VARCHAR2(50),  -- Degenerate Dimension
    line_nbr        NUMBER,        -- Line Number for uniqueness
    
    -- Foreign Keys
    customer_sk     NUMBER REFERENCES dim_customer(customer_sk),
    product_sk      NUMBER REFERENCES dim_product(product_sk),
    shipment_sk     NUMBER REFERENCES dim_shipment(shipment_sk),
    junk_sk         NUMBER REFERENCES dim_junk(junk_sk),
    date_sk         NUMBER REFERENCES dim_date(date_sk),
    
    -- Measures
    quantity        NUMBER,
    unit_price      NUMBER(10,2),
    discount_rate   NUMBER(5,2),
    line_net_amount NUMBER(10,2),
    line_vat_amount NUMBER(10,2)
);